--changeset jamesmckeon:create-orders-table
CREATE TABLE orders.orders (
    order_id uuid NOT NULL,
    owner_id integer NOT NULL,
    purchase_order_number character varying(50) NOT NULL,
    reference_number character varying(50) NOT NULL,
    street_address_one character varying(150) NOT NULL,
    street_address_two character varying(150),
    city character varying(50) NOT NULL,
    state character(2) NOT NULL,
    zipcode character varying(10) NOT NULL,
    created_date timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT pk_orders PRIMARY KEY (order_id)
);
--rollback DROP TABLE orders.orders;

--changeset jamesmckeon:create-order-lines-table
CREATE TABLE orders.order_lines (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    order_id uuid NOT NULL,
    sku_code character varying(50) NOT NULL,
    quantity integer NOT NULL,
    created_date timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT pk_order_lines PRIMARY KEY (id)
);
--rollback DROP TABLE orders.order_lines;

--changeset jamesmckeon:add-order-lines-orders-fk
ALTER TABLE orders.order_lines
    ADD CONSTRAINT fk_order_lines_orders_order_id FOREIGN KEY (order_id)
        REFERENCES orders.orders (order_id) ON DELETE CASCADE;
--rollback ALTER TABLE orders.order_lines DROP CONSTRAINT fk_order_lines_orders_order_id;

--changeset jamesmckeon:create-order-lines-order-id-index
CREATE INDEX ix_order_lines_order_id ON orders.order_lines (order_id);
--rollback DROP INDEX orders.ix_order_lines_order_id;

--changeset jamesmckeon:create-orders-owner-reference-unique-index
